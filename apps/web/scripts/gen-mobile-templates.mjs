#!/usr/bin/env node
// Generates mobile/src/templates.gen.ts from the web TEMPLATES registry
// (types/index.ts). Deterministic — re-run whenever the web registry changes:
//   node scripts/gen-mobile-templates.mjs
// The mobile app must mirror the web's template catalogue for the picker.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "types/index.ts"), "utf8");

const block = src.slice(src.indexOf("export const TEMPLATES"));
const re =
  /\{ id: "([^"]+)",\s+name: "([^"]+)",\s+description: "([^"]*)",\s+previewColor: "([^"]+)",\s+style: "(\w+)"(?:,\s+popular: (true))?/g;

const out = [];
let m;
while ((m = re.exec(block)) !== null) {
  out.push({
    id: m[1],
    name: m[2],
    description: m[3],
    previewColor: m[4],
    style: m[5],
    popular: m[6] === "true",
  });
}

if (!out.length) {
  console.error("No templates parsed — registry format changed?");
  process.exit(1);
}

const lines = out.map(
  (t) =>
    `  { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, description: ${JSON.stringify(t.description)}, previewColor: ${JSON.stringify(t.previewColor)}, style: ${JSON.stringify(t.style)}, popular: ${t.popular} },`,
);

const gen = `// GENERATED by scripts/gen-mobile-templates.mjs — DO NOT EDIT.
// Mirrors the web TEMPLATES registry (types/index.ts) for the native picker.
import type { NativeTemplate } from "./types";

export const ALL_TEMPLATES: NativeTemplate[] = [
${lines.join("\n")}
];
`;

const dest = join(root, "mobile/src/templates.gen.ts");
writeFileSync(dest, gen);
console.log(`Wrote ${out.length} templates → mobile/src/templates.gen.ts`);
